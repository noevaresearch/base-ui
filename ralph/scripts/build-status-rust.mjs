#!/usr/bin/env node
/* eslint-disable no-console */

// build-status-rust.mjs — status.json -> crates/docs-app/src/status_data.rs
//
// Split from build-status.mjs on purpose: the JSON producer aggregates gate outputs, and this turns the
// result into compile-time Rust the /status page renders. Two small steps beat one file with nested template
// literals — the first attempt at that failed with "Identifier 'rows' has already been declared" and took the
// whole generator down, which is a silly way to lose a progress table.
//
// Compile-time rather than a runtime fetch: no JSON dependency in the wasm app, nothing to 404 on the
// deployed site, and a build that fails loudly if the data is malformed.
//
// Usage: node ralph/scripts/build-status-rust.mjs   (run after build-status.mjs)

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../..');
const SRC = path.join(ROOT, 'crates/docs-app/status.json');
const OUT = path.join(ROOT, 'crates/docs-app/src/status_data.rs');

const data = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const opt = (v) => (v === null || v === undefined ? 'None' : `Some(${v})`);
const str = (v) => (v === null || v === undefined ? 'None' : `Some(${JSON.stringify(v)})`);
const numf = (v) => (v === null || v === undefined ? 'None' : `Some(${Number(v)}${Number.isInteger(Number(v)) ? '.0' : ''})`);

const lines = data.components.map((c) => [
  '    ComponentStatus {',
  `        component: ${JSON.stringify(c.component)},`,
  `        parts_exposed: ${opt(c.parts ? c.parts.exposed : null).replace('Some(', 'Some(').replace(/(\d+)\)/, '$1u32)')},`,
  `        parts_documented: ${c.parts ? `Some(${c.parts.documented}u32)` : 'None'},`,
  `        namespaced_path: ${str(c.namespacedPath)},`,
  `        snippets_leptos: ${c.snippets ? `Some(${c.snippets.leptos}u32)` : 'None'},`,
  `        snippets_react: ${c.snippets ? `Some(${c.snippets.react}u32)` : 'None'},`,
  `        example_length_pct: ${numf(c.exampleLengthPct)},`,
  `        attribute_ratio: ${numf(c.attributeRatio)},`,
  `        copy_coverage: ${numf(c.copyCoverage)},`,
  `        page_parity: ${numf(c.pageParity)},`,
  `        widget_parity: ${numf(c.widgetParity)},`,
  `        page_verdict: ${str(c.pageVerdict)},`,
  '    },',
].join('\n')).join('\n');

const rust = `//! @generated by ralph/scripts/build-status-rust.mjs (from status.json) — DO NOT EDIT BY HAND.
//!
//! The per-component progress table the docs site's /status page renders. Regenerated before the site build
//! (see .github/workflows/deploy-docs-app.yml), so the page shows the state of the port at the commit being
//! deployed. Every field comes from a gate's own output — parts from \`check-part-surface --json\`, snippets
//! from \`snippet-ergonomics\`, copy from \`check-copy-fidelity\`, parity from the visual baseline, verdicts
//! from the page scorecard — so the page cannot drift from the numbers the loop is held to.
//!
//! A field that could not be measured is \`None\` and renders as "unmeasured", NEVER as a pass.

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ComponentStatus {
    pub component: &'static str,
    pub parts_exposed: Option<u32>,
    pub parts_documented: Option<u32>,
    pub namespaced_path: Option<&'static str>,
    pub snippets_leptos: Option<u32>,
    pub snippets_react: Option<u32>,
    pub example_length_pct: Option<f64>,
    pub attribute_ratio: Option<f64>,
    pub copy_coverage: Option<f64>,
    pub page_parity: Option<f64>,
    pub widget_parity: Option<f64>,
    pub page_verdict: Option<&'static str>,
}

pub const GENERATED_AT: &str = ${JSON.stringify(data.generatedAt)};
pub const ITEMS_DONE: u32 = ${data.headline.itemsDone};
pub const ITEMS_TOTAL: u32 = ${data.headline.itemsTotal};
pub const ITEMS_PCT: f64 = ${data.headline.itemsPct};
pub const PAGES_MEASURED: u32 = ${data.headline.pagesMeasured};
pub const PAGES_PASSING: u32 = ${data.headline.pagesPassing};
pub const MIRRORED_ROUTES: u32 = ${data.headline.mirroredRoutes};
pub const EXPLANATION: &str = ${JSON.stringify(data.headline.explanation)};

pub const COMPONENTS: &[ComponentStatus] = &[
${lines}
];
`;

fs.writeFileSync(OUT, rust);
console.log(`status_data.rs written: ${data.components.length} component(s)`);
